void main() async {
  // 1. Ensure Flutter is ready
  WidgetsFlutterBinding.ensureInitialized();

  // 2. Initialize Firebase (This connects your app to the cloud)
  await Firebase.initializeApp(
    options: DefaultFirebaseOptions.currentPlatform,
  );

  // 3. Inject Repositories (So they are ready for the Controllers to use)
  Get.put(ExpenseRepository());
  Get.put(UserRepository());
  Get.put(AuthRepository());
  Get.put(DashboardController());
  Get.put(Usercontroller());

  runApp(const MyApp());
}

class MyApp extends StatelessWidget {
  const MyApp({super.key});

  @override
  Widget build(BuildContext context) {
    return ScreenUtilInit(
      designSize: const Size(375, 812),
      minTextAdapt: true,
      splitScreenMode: true,
      builder: (_, child) {
        return GetMaterialApp(
          debugShowCheckedModeBanner: false,
          theme: ThemeData(
            // Optional: Setting a global theme here
            brightness: Brightness.dark,
          ),
          // Using DashboardScreen as the starting point as requested
          home: LoginView(),
        );
      },
    );
  }
}